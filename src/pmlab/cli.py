"""Command-line interface.

pmlab irr flows.csv                     every IRR, the multiples and (with --index) every PME of a cash-flow file
pmlab market fetch                      store the index histories the PMEs are measured against
pmlab validate --out docs/VALIDATION.md the validation suite
pmlab gallery                           every chart in the documentation
"""

from __future__ import annotations

import argparse
import sys
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import pandas as pd

from .cashflows import CashFlows, irr_roots, mirr, multiples, sign_changes


def cmd_irr(args: argparse.Namespace) -> None:
    """A CSV with columns ``date`` and ``amount`` (investor's side); optional ``nav`` on the last row's date."""
    frame = pd.read_csv(args.file, parse_dates=["date"]).sort_values("date")
    cf = CashFlows.from_dates([d.date() for d in frame["date"]], frame["amount"].to_numpy(float), args.nav)
    t, a = cf.with_nav()
    roots = irr_roots(t, a)
    m = multiples(cf)
    print(
        f"{len(frame)} flows over {t[-1]:.2f} years; paid in {m.paid_in:,.2f}, distributed "
        f"{m.distributed:,.2f}, NAV {m.residual:,.2f}"
    )
    print(f"DPI {m.dpi:.3f}  RVPI {m.rvpi:.3f}  TVPI {m.tvpi:.3f}")
    label = "IRR" if len(roots) == 1 else f"IRRs ({len(roots)}; Descartes allows {sign_changes(a)})"
    print(f"{label}: " + (", ".join(f"{100 * r:.4f}%" for r in roots) or "none"))
    print(f"MIRR at {args.finance:.1%} / {args.reinvest:.1%}: {100 * mirr(t, a, args.finance, args.reinvest):.4f}%")
    if args.index:
        from . import market
        from .pme import report

        series = market.load(args.index)
        levels = np.interp(frame["date"].astype("int64").to_numpy(), series.index.astype("int64").to_numpy(), series.to_numpy())
        r = report(cf.times, cf.amounts, levels, cf.nav)
        print(f"against {market.LABELS[args.index]}:")
        print(f"  Kaplan-Schoar PME {r.ks_pme:.4f}   Direct Alpha {100 * r.direct_alpha:.3f}% a year")
        ln = "no unique IRR (the index account went negative)" if np.isnan(r.ln_irr) else f"{100 * r.ln_irr:.3f}%"
        print(f"  Long-Nickels index IRR {ln}   PME+ index IRR {100 * r.pme_plus_irr:.3f}%")


def cmd_market(args: argparse.Namespace) -> None:
    from . import market

    if args.action == "fetch":
        print(f"stored {market.fetch()}")
        return
    if not market.available():
        print(f"no index history under {market.data_root()}; run `pmlab market fetch`")
        return
    for name in market.TICKERS:
        s = market.load(name)
        print(f"{name:<7} {market.LABELS[name]:<24} {s.index[0]:%Y-%m} to {s.index[-1]:%Y-%m}, {len(s)} months")


def cmd_validate(args: argparse.Namespace) -> None:
    from .validation import run_validation, to_markdown

    results = run_validation(fast=args.fast)
    table = to_markdown(results)
    print(table)
    if args.out:
        header = (
            "# Validation report\n\n"
            f"Generated by `pmlab validate` on {datetime.now(timezone.utc):%Y-%m-%d}. Every measure is held to a published "
            "value, an independent method, or an identity that must hold.\n\n"
        )
        Path(args.out).write_text(header + table + "\n", encoding="utf-8")
    if not results["passed"].all():
        sys.exit(1)


def cmd_gallery(args: argparse.Namespace) -> None:
    from . import gallery

    written = gallery.build(args.out, only=args.only)
    if args.only is None:
        Path("docs").mkdir(exist_ok=True)
        Path("docs/GALLERY.md").write_text(gallery.markdown() + "\n", encoding="utf-8")
    print(f"{len(written)} charts written to {args.out}")


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="pmlab", description="Private markets and alternative investments, measured.")
    sub = parser.add_subparsers(dest="command", required=True)

    one = sub.add_parser("irr", help="every IRR, the multiples and the PMEs of a cash-flow file")
    one.add_argument("file", help="CSV with columns date, amount (contributions negative)")
    one.add_argument("--nav", type=float, default=0.0, help="net asset value at the last date")
    one.add_argument("--finance", type=float, default=0.08, help="MIRR finance rate")
    one.add_argument("--reinvest", type=float, default=0.08, help="MIRR reinvestment rate")
    one.add_argument("--index", choices=["sp500", "small", "nasdaq", "value"], default=None, help="benchmark for the PMEs")
    one.set_defaults(func=cmd_irr)

    data = sub.add_parser("market", help="store the index histories from Yahoo Finance, or list them")
    data.add_argument("action", choices=["fetch", "list"])
    data.set_defaults(func=cmd_market)

    validate = sub.add_parser("validate", help="run the validation suite")
    validate.add_argument("--out", default=None)
    validate.add_argument("--fast", action="store_true")
    validate.set_defaults(func=cmd_validate)

    charts = sub.add_parser("gallery", help="redraw the documentation's charts")
    charts.add_argument("--out", default="docs/images")
    charts.add_argument("--only", default=None, help="one chart's file name, or a day's number")
    charts.set_defaults(func=cmd_gallery)
    return parser


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    args.func(args)


if __name__ == "__main__":
    main()
